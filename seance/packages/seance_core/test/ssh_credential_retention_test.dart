// An authenticated client must not keep the credentials it signed in with:
// a key's passphrase opens the key for the sign-in only, and an app that
// asks for it on each connect (Klabautermann's O5) promises not to keep it
// past the attempt. The client lives as long as the connection and holds
// the callbacks it was given, so anything those callbacks' scope captured
// lives as long too.
import 'dart:async';
import 'dart:math';
import 'dart:typed_data';

import 'package:dartssh2/dartssh2.dart';
import 'package:seance_core/seance_core.dart';
import 'package:test/test.dart';

import 'support/ssh_peer.dart';

final _config = ServerConfig(
  id: 'test',
  label: 'test',
  host: 'unused.invalid',
  username: 'user',
  authMethod: AuthMethod.privateKey,
  createdAt: 0,
  updatedAt: 0,
);

String _encryptedKeyPem(String passphrase) {
  final random = Random.secure();
  Uint8List randomBytes(int length) => Uint8List.fromList(
    List<int>.generate(length, (_) => random.nextInt(256)),
  );
  final publicKey = randomBytes(32);
  return OpenSSHEd25519KeyPair(
    publicKey,
    Uint8List.fromList([...randomBytes(32), ...publicKey]),
    'generated by ssh_credential_retention_test',
  ).toPem(passphrase: passphrase, rounds: 1);
}

/// Signs in to an in-process peer with an encrypted key and its
/// passphrase. Returns the client, which the caller keeps open, and a weak
/// reference to the credentials, which nothing else holds.
Future<(SSHClient, WeakReference<SshCredentials>)> _signIn(
  SshPeerSocket socket,
) async {
  final credentials = SshCredentials.privateKey(
    _encryptedKeyPem('right'),
    keyPassphrase: 'right',
  );
  final (client, _) = await openAuthenticatedClient(
    config: _config,
    credentials: credentials,
    tofu: TofuVerifier(InMemoryHostKeyStore()),
    // The peer runs a real key exchange; host-key trust is not under test.
    onHostKey: (_) async => true,
    connect: (_, _, _) async => socket,
    keepAliveInterval: null,
  );
  return (client, WeakReference(credentials));
}

/// As [_signIn], through `SshLink.connect`, which wraps the callbacks it
/// hands the client.
Future<(SshLink, WeakReference<SshCredentials>)> _link(
  SshPeerSocket socket,
) async {
  final credentials = SshCredentials.privateKey(
    _encryptedKeyPem('right'),
    keyPassphrase: 'right',
  );
  final link = await SshLink.connect(
    config: _config,
    credentials: credentials,
    tofu: TofuVerifier(InMemoryHostKeyStore()),
    onHostKey: (_) async => true,
    connect: (_, _, _) async => socket,
  );
  return (link, WeakReference(credentials));
}

/// Allocates until [reference] clears or a generous budget runs out: no
/// public API forces a collection, and allocation pressure runs both the
/// young and the old generation's collector.
Future<bool> _collected(WeakReference<Object> reference) async {
  final garbage = <Uint8List>[];
  for (var i = 0; i < 512 && reference.target != null; i++) {
    garbage.add(Uint8List(1 << 20));
    if (garbage.length > 32) garbage.clear();
    await Future<void>.delayed(Duration.zero);
  }
  return reference.target == null;
}

void main() {
  test('an open client keeps no reference to the credentials, so a key '
      'passphrase does not outlive the sign-in', () async {
    final socket = SshPeerSocket();
    final (client, credentials) = await _signIn(socket);
    addTearDown(client.close);

    expect(await _collected(credentials), isTrue);
    // The client is still in use: it holds its callbacks until it closes.
    expect(client.isClosed, isFalse);
  });

  test('neither does an open SshLink', () async {
    final socket = SshPeerSocket();
    final (link, credentials) = await _link(socket);
    addTearDown(link.close);

    expect(await _collected(credentials), isTrue);
    expect(link.state, isA<SshLinkReady>());
  });
}

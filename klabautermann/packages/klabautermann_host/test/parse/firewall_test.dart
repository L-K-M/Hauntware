const _iptables = '''
# Generated by iptables-save v1.8.10 (nf_tables) on Mon Oct 26 15:00:00 2026
*filter
:INPUT DROP [0:0]
:FORWARD DROP [0:0]
:OUTPUT ACCEPT [0:0]
:DOCKER - [0:0]
-A INPUT -i lo -j ACCEPT
-A INPUT -p tcp -m tcp --dport 22 -j ACCEPT
-A FORWARD -j DOCKER
COMMIT
*nat
:PREROUTING ACCEPT [0:0]
-A PREROUTING -m addrtype --dst-type LOCAL -j DOCKER
COMMIT
''';

void main() {
  test('ufw gives its state, default policies and rules', () {
    final ufw = parseFirewall('$kFirewallUfwMarker\n$_ufw')!.ufw!;
    expect(ufw.active, isTrue);
    expect(
      (ufw.incoming, ufw.outgoing, ufw.routed),
      ('deny', 'allow', 'disabled'),
    );
    expect(
      [for (final rule in ufw.rules) '${rule.to}|${rule.action}|${rule.from}'],
      [
        '22/tcp|ALLOW IN|Anywhere',
        '80,443/tcp (Nginx Full)|ALLOW IN|Anywhere',
        '8080|DENY IN|192.0.2.0/24',
        '22/tcp (v6)|ALLOW IN|Anywhere (v6)',
      ],
    );
    final inactive = parseFirewall('$kFirewallUfwMarker\nStatus: inactive\n')!;
    expect(inactive.ufw!.active, isFalse);
    expect(inactive.ufw!.rules, isEmpty);
  });

  test('firewalld lists each zone, the default and active ones marked', () {
    final firewalld = parseFirewall(
      '$kFirewallFirewalldMarker running\n$_zones',
    )!.firewalld!;
    expect(firewalld.running, isTrue);
    final [block, public, trusted] = firewalld.zones;
    expect(
      (block.name, block.active, block.target),
      ('block', false, '%%REJECT%%'),
    );
    expect(public.isDefault, isTrue);
    expect(public.active, isTrue);
    expect(public.interfaces, ['eth0', 'eth1']);
    expect(public.services, ['dhcpv6-client', 'ssh']);
    expect(public.ports, ['8080/tcp', '9000-9010/udp']);
    expect(public.sources, isEmpty);
    expect(trusted.sources, ['10.0.0.0/8']);
    expect(trusted.isDefault, isFalse);

    final stopped = parseFirewall(
      '$kFirewallFirewalldMarker not running\n',
    )!.firewalld!;
    expect(stopped.running, isFalse);
    expect(stopped.zones, isEmpty);
  });

  test('nftables counts each chain\'s rules', () {
    final chains = parseFirewall('$kFirewallNftMarker\n$_nft\n')!.nftables!;
    final [input, allowed] = chains;
    expect(
      (input.family, input.table, input.name, input.hook, input.policy),
      ('inet', 'filter', 'input', 'input', 'drop'),
    );
    expect(input.rules, 3);
    expect(allowed.hook, isNull);
    expect(allowed.policy, isNull);
    expect(allowed.rules, 0);

    // An empty ruleset, and output cut mid-write.
    final empty = parseFirewall(
      '$kFirewallNftMarker\n{"nftables": [{"metainfo": {}}]}\n',
    )!;
    expect(empty.nftables, isEmpty);
    final cut = parseFirewall('$kFirewallNftMarker\n{"nftables": [{"tab\n')!;
    expect(cut.nftables, isEmpty);
  });

  test('iptables-save gives each table\'s chains with policy and rules', () {
    final read = parseFirewall(
      '$kFirewallIptablesMarker\n$_iptables$kFirewallIp6tablesMarker\n',
    )!;
    expect(
      [
        for (final c in read.iptables!)
          '${c.table} ${c.name} ${c.policy} ${c.rules}',
      ],
      [
        'filter INPUT drop 2',
        'filter FORWARD drop 1',
        'filter OUTPUT accept 0',
        'filter DOCKER null 0',
        'nat PREROUTING accept 1',
      ],
    );
    expect(read.ip6tables, isEmpty);
  });

  test('no tool reads as none; other output is not the read', () {
    final none = parseFirewall('')!;
    expect(none.noTool, isTrue);
    expect(
      parseFirewall('$kFirewallNftMarker\n{"nftables": []}\n')!.noTool,
      isFalse,
    );
    expect(parseFirewall('sh: 1: ufw: Permission denied\n'), isNull);
  });
}

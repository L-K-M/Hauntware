// Regenerates lib/src/unicode_case_fold_data.dart, the full case folding a
// case-insensitive plain-text search uses, from the pinned CaseFolding.txt
// beside this script. Offline: the fixture is checked in and its hash is
// verified, so the table changes only when the pinned version does.
import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';

const _unicodeVersion = '17.0.0';
const _sourceSha256 =
    'ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183';
const _sourceUrl =
    'https://www.unicode.org/Public/$_unicodeVersion/ucd/CaseFolding.txt';

/// CaseFolding.txt statuses: common mappings shared by simple and full
/// folding, and full folding's expansions. Simple-only (S) and Turkic (T)
/// mappings are not part of full folding.
const _commonStatus = 'C';
const _fullStatus = 'F';

/// The first supplementary code point. A common mapping must stay on its
/// side of it: the search folds UTF-16 runs in place and relies on a fold
/// never changing a run's length.
const _firstSupplementary = 0x10000;

void main() {
  final source = File.fromUri(
    Platform.script.resolve('CaseFolding-$_unicodeVersion.txt'),
  );
  final bytes = source.readAsBytesSync();
  if (sha256.convert(bytes).toString() != _sourceSha256) {
    throw StateError('CaseFolding.txt differs from the pinned release.');
  }

  final common = <({int source, int target})>[];
  final expansions = <({int source, List<int> targets})>[];
  for (final line in const LineSplitter().convert(utf8.decode(bytes))) {
    if (line.isEmpty || line.startsWith('#')) continue;
    final fields = line.split(';').map((field) => field.trim()).toList();
    final point = int.parse(fields[0], radix: 16);
    final targets = [
      for (final value in fields[2].split(' ')) int.parse(value, radix: 16),
    ];
    switch (fields[1]) {
      case _commonStatus:
        if (targets.length != 1 ||
            (point < _firstSupplementary) !=
                (targets.single < _firstSupplementary)) {
          throw StateError('Common mapping ${fields[0]} changes length.');
        }
        common.add((source: point, target: targets.single));
      case _fullStatus:
        // The search scans expansions one UTF-16 unit at a time.
        if (point >= _firstSupplementary) {
          throw StateError('Full mapping ${fields[0]} is not one unit.');
        }
        expansions.add((source: point, targets: targets));
    }
  }

  final output = StringBuffer()
    ..writeln('// Generated by tool/unicode/generate.dart. Do not edit.')
    ..writeln('// Source: $_sourceUrl')
    ..writeln('// SHA-256: $_sourceSha256')
    ..writeln(
      '// Copyright © 1991-2026 Unicode, Inc. License: tool/unicode/LICENSE.txt',
    )
    ..writeln()
    ..writeln("part of 'search_fold.dart';")
    ..writeln()
    ..writeln('/// The Unicode version the tables below come from.')
    ..writeln("const unicodeCaseFoldingVersion = '$_unicodeVersion';")
    ..writeln()
    ..writeln('// Status C mappings, one range per constant offset; stride 2')
    ..writeln('// steps over the lowercase letters of alternating runs.')
    ..writeln('// dart format off')
    ..writeln(
      'const _commonFoldRanges = '
      '<({int start, int end, int stride, int delta})>[',
    );
  for (final range in _ranges(common)) {
    output.writeln(
      '  (start: ${_hex(range.start)}, end: ${_hex(range.end)}, '
      'stride: ${range.stride}, delta: ${range.delta}),',
    );
  }
  output
    ..writeln('];')
    ..writeln()
    ..writeln('// Status F mappings: characters whose full fold is longer.')
    ..writeln('const _fullFoldExpansions = <int, String>{');
  for (final expansion in expansions) {
    final targets = expansion.targets.map(_escape).join();
    output.writeln("  ${_hex(expansion.source)}: '$targets',");
  }
  output
    ..writeln('};')
    ..writeln('// dart format on');

  File.fromUri(
    Platform.script.resolve('../../lib/src/unicode_case_fold_data.dart'),
  ).writeAsStringSync(output.toString());
  stdout.writeln(
    '${common.length} common mappings; ${expansions.length} expansions.',
  );
}

/// Collapses consecutive mappings with the same offset, at stride 1 or 2,
/// into ranges. CaseFolding.txt lists code points in ascending order.
List<({int start, int end, int stride, int delta})> _ranges(
  List<({int source, int target})> mappings,
) {
  final ranges = <({int start, int end, int stride, int delta})>[];
  for (var index = 0; index < mappings.length;) {
    final first = mappings[index];
    final delta = first.target - first.source;
    var end = index;
    var stride = 1;
    if (index + 1 < mappings.length) {
      final next = mappings[index + 1];
      final distance = next.source - first.source;
      if (distance <= 2 && next.target - next.source == delta) {
        stride = distance;
        end++;
      }
    }
    while (end + 1 < mappings.length &&
        mappings[end + 1].source - mappings[end].source == stride &&
        mappings[end + 1].target - mappings[end + 1].source == delta) {
      end++;
    }
    ranges.add((
      start: first.source,
      end: mappings[end].source,
      stride: stride,
      delta: delta,
    ));
    index = end + 1;
  }
  return ranges;
}

String _hex(int value) => '0x${value.toRadixString(16)}';

String _escape(int point) => '\\u{${point.toRadixString(16)}}';
